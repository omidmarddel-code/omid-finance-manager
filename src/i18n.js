export function t(value) {
  if (currentLanguage !== "en") return value;
  if (translations[value]) return translations[value];
  return mixedPhrases.reduce(
    (text, [fa, en]) => text.replaceAll(fa, en),
    value,
  );
}
export function displayCategory(value) {
  return currentLanguage === "en" ? translations[value] || value : value;
}

export function localizeDOM(root) {
  if (!root || currentLanguage !== "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const value = node.nodeValue;
    if (
      node.parentElement?.closest(
        ".transaction-main b,.installment-head h2,.category-chips span",
      )
    )
      continue;
    const trimmed = value.trim();
    if (!trimmed) continue;
    if (translations[trimmed]) {
      node.nodeValue = value.replace(trimmed, translations[trimmed]);
      continue;
    }
    let translated = value;
    for (const [fa, en] of mixedPhrases)
      translated = translated.replaceAll(fa, en);
    if (translated !== value) node.nodeValue = translated;
  }
  root
    .querySelectorAll("[placeholder],[title],[aria-label]")
    .forEach((element) => {
      for (const attribute of ["placeholder", "title", "aria-label"]) {
        const value = element.getAttribute(attribute);
        if (value && translations[value])
          element.setAttribute(attribute, translations[value]);
      }
    });
}
